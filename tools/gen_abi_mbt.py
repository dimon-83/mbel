#!/usr/bin/env python3
"""Emits playground/web/manifest_generated.mbt from playground/mbel.abi.json.

The JSON is canonical (single source): version, export list, host
requirements and the error-code vocabulary live there once, and
`describe_abi()` returns this generated literal. CI runs

    python3 tools/gen_abi_mbt.py --check

so a hand edit to the JSON without regenerating — or a hand edit to the
generated file — fails the build instead of shipping a manifest that
disagrees with the artifact.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "playground" / "mbel.abi.json"
OUT_PATH = ROOT / "playground" / "web" / "manifest_generated.mbt"
CHUNK = 96


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def render(manifest: dict) -> str:
    payload = json.dumps(manifest, ensure_ascii=False, separators=(",", ":"))
    chunks = [payload[i : i + CHUNK] for i in range(0, len(payload), CHUNK)]
    body = " +\n".join(f'  "{escape(chunk)}"' for chunk in chunks)
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// @generated by tools/gen_abi_mbt.py from playground/mbel.abi.json.\n"
        "// Do not edit by hand: change the JSON, then regenerate.\n"
        "// Regenerate: python3 tools/gen_abi_mbt.py\n"
        "// Verify:     python3 tools/gen_abi_mbt.py --check\n"
        "\n"
        "///|\n"
        "/// The canonical ABI manifest, byte-identical to\n"
        "/// playground/mbel.abi.json (minified). Generated so the version and\n"
        "/// export list have exactly one source.\n"
        "fn abi_manifest() -> String {\n"
        f"{body}\n"
        "}\n"
    )


def main(argv: list[str]) -> int:
    manifest = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    expected = render(manifest)
    if "--check" in argv:
        actual = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else ""
        if actual != expected:
            print(
                "manifest_generated.mbt is stale: run python3 tools/gen_abi_mbt.py",
                file=sys.stderr,
            )
            return 1
        print(f"manifest OK: {OUT_PATH.relative_to(ROOT)} matches the JSON")
        return 0
    OUT_PATH.write_text(expected, encoding="utf-8")
    print(f"wrote {OUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
